def tr(key: str, language: str = "en", **values: Any) -> str:
    catalog = _JAPANESE if language == "ja" else _ENGLISH
    template = catalog.get(key, _ENGLISH.get(key, key))
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


def ui_text(text: str, language: str | None = None) -> str:
    """Translate a visible English UI phrase while leaving user data untouched."""
    if language is None:
        try:
            from PySide6.QtWidgets import QApplication

            application = QApplication.instance()
            language = (
                str(application.property("ui_language") or "en")
                if application is not None
                else "en"
            )
        except ImportError:
            language = "en"
    if language != "ja":
        return text
    exact = _JA_TEXT.get(text)
    if exact is not None:
        return exact
    for source, translated in _JA_FORMATS:
        names = re.findall(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}", source)
        parts = re.split(r"\{[a-zA-Z_][a-zA-Z0-9_]*\}", source)
        expression = "^" + r"(.*?)".join(re.escape(part) for part in parts) + "$"
        match = re.fullmatch(expression, text, flags=re.DOTALL)
        if match is not None:
            values = dict(zip(names, match.groups(), strict=True))
            return translated.format(**values)
    return text


def set_ui_text(widget: Any, source_text: str, language: str | None = None) -> None:
    """Set a translatable QLabel-like string while retaining its source copy."""
    if hasattr(widget, "setProperty"):
        widget.setProperty("_eli_i18n_text", str(source_text))
    widget.setText(ui_text(str(source_text), language))


def set_ui_format(widget: Any, source_format: str, language: str | None = None) -> None:
    """Set a translatable QProgressBar format while retaining its source copy."""
    if hasattr(widget, "setProperty"):
        widget.setProperty("_eli_i18n_format", str(source_format))
    widget.setFormat(ui_text(str(source_format), language))


def apply_widget_translations(root: Any, language: str = "en") -> None:
    """Translate static Qt widget copy while preserving user-entered text and IDs."""
    try:
        from PySide6.QtGui import QAction
        from PySide6.QtWidgets import (
            QAbstractButton,
            QComboBox,
            QGroupBox,
            QLabel,
            QLineEdit,
            QMenu,
            QPlainTextEdit,
            QProgressBar,
            QTabWidget,
            QTableWidget,
            QTextEdit,
            QTreeWidget,
            QWidget,
        )
    except ImportError:
        return

    try:
        from PySide6.QtWidgets import QApplication

        qt_application = QApplication.instance()
        if qt_application is not None:
            qt_application.setProperty("ui_language", language)
    except ImportError:
        pass

    def original(obj: Any, property_name: str, current: Any) -> Any:
        stored = obj.property(property_name)
        if stored is None:
            obj.setProperty(property_name, current)
            return current
        return stored

    widgets = [root, *root.findChildren(QWidget)]
    for widget in widgets:
        if widget.windowTitle():
            source_title = original(
                widget, "_eli_i18n_window_title", widget.windowTitle()
            )
            widget.setWindowTitle(ui_text(str(source_title), language))
        if isinstance(widget, QMenu):
            source_menu_title = original(widget, "_eli_i18n_menu_title", widget.title())
            widget.setTitle(ui_text(str(source_menu_title), language))
        if isinstance(widget, QLabel):
            source = original(widget, "_eli_i18n_text", widget.text())
            widget.setText(ui_text(str(source), language))
        if isinstance(widget, QAbstractButton):
            source = original(widget, "_eli_i18n_text", widget.text())
            widget.setText(ui_text(str(source), language))
        if isinstance(widget, QGroupBox):
            source = original(widget, "_eli_i18n_group_title", widget.title())
            widget.setTitle(ui_text(str(source), language))
        if isinstance(widget, QLineEdit):
            source = original(
                widget, "_eli_i18n_placeholder", widget.placeholderText()
            )
            widget.setPlaceholderText(ui_text(str(source), language))
        if isinstance(widget, (QPlainTextEdit, QTextEdit)):
            source = original(
                widget, "_eli_i18n_placeholder", widget.placeholderText()
            )
            widget.setPlaceholderText(ui_text(str(source), language))
        if isinstance(widget, QComboBox):
            # Store each item's source label in a private item-data role.
            # This survives language changes and combo clears/repopulation.
            source_role = int(Qt.ItemDataRole.UserRole) + 173
            for index in range(widget.count()):
                source = widget.itemData(index, source_role)
                if source is None:
                    source = widget.itemText(index)
                    widget.setItemData(index, str(source), source_role)
                widget.setItemText(index, ui_text(str(source), language))
        if isinstance(widget, QTabWidget):
            current_tabs = [widget.tabText(i) for i in range(widget.count())]
            source_tabs = original(
                widget, "_eli_i18n_tabs", current_tabs
            )
            for index, source in enumerate(source_tabs):
                if index < widget.count():
                    widget.setTabText(index, ui_text(str(source), language))

        header_role = int(Qt.ItemDataRole.UserRole) + 174
        if isinstance(widget, QTableWidget):
            for index in range(widget.columnCount()):
                header_item = widget.horizontalHeaderItem(index)
                if header_item is None:
                    continue
                source = header_item.data(header_role)
                if source is None:
                    source = header_item.text()
                    header_item.setData(header_role, str(source))
                header_item.setText(ui_text(str(source), language))
        if isinstance(widget, QTreeWidget):
            header_item = widget.headerItem()
            if header_item is not None:
                for index in range(widget.columnCount()):
                    source = header_item.data(index, header_role)
                    if source is None:
                        source = header_item.text(index)
                        header_item.setData(index, header_role, str(source))
                    header_item.setText(index, ui_text(str(source), language))
        if isinstance(widget, QProgressBar):
            source_format = original(
                widget, "_eli_i18n_format", widget.format()
            )
            widget.setFormat(ui_text(str(source_format), language))

        source_tooltip = original(
            widget, "_eli_i18n_tooltip", widget.toolTip()
        )
        if source_tooltip:
            widget.setToolTip(ui_text(str(source_tooltip), language))
        source_accessible = original(
            widget, "_eli_i18n_accessible_name", widget.accessibleName()
        )
        if source_accessible:
            widget.setAccessibleName(ui_text(str(source_accessible), language))

    for action in root.findChildren(QAction):
        source_text = original(action, "_eli_i18n_text", action.text())
        action.setText(ui_text(str(source_text), language))
        source_tip = original(action, "_eli_i18n_tooltip", action.toolTip())
        if source_tip:
            action.setToolTip(ui_text(str(source_tip), language))
        source_status = original(
            action, "_eli_i18n_status_tip", action.statusTip()
        )
        if source_status:
            action.setStatusTip(ui_text(str(source_status), language))
